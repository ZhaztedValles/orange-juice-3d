// Writes src/videos.generated.ts from videos/<id>/Video.tsx (+ words.json when present), sorted by id.
// usage: node scripts/gen-registry.mjs [--check]
//   --check  compare instead of writing; exit 1 when the registry is out of date
// Folder names must match NNN-slug (e.g. 000-bridge); other folders are skipped with a warning.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VIDEOS = path.join(ROOT, "videos");
const OUT = path.join(ROOT, "src", "videos.generated.ts");
const ID = /^\d{3}-[a-z0-9-]+$/;

export const scan = (dir = VIDEOS) => {
  const ids = [];
  for (const e of fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }) : []) {
    if (!e.isDirectory() || !fs.existsSync(path.join(dir, e.name, "Video.tsx"))) continue;
    if (!ID.test(e.name)) { console.warn(`gen-registry: skipping videos/${e.name} (folder name must match NNN-slug)`); continue; }
    ids.push(e.name);
  }
  ids.sort();
  const seen = new Map();
  for (const id of ids) {
    const n = id.slice(0, 3);
    if (seen.has(n)) throw new Error(`gen-registry: videos/${seen.get(n)} and videos/${id} share the number ${n}`);
    seen.set(n, id);
  }
  return ids.map((id) => ({ id, n: id.slice(0, 3), words: fs.existsSync(path.join(dir, id, "words.json")) }));
};

export const render = (videos) => {
  const L = [
    "// GENERATED by scripts/gen-registry.mjs - do not edit",
    'import type React from "react";',
    'import type { Word } from "./engine/captions";',
  ];
  for (const v of videos) {
    L.push(`import V${v.n}, { FRAMES as F${v.n} } from "../videos/${v.id}/Video";`);
    if (v.words) L.push(`import W${v.n} from "../videos/${v.id}/words.json";`);
  }
  L.push(
    "",
    "export type VideoEntry = { id: string; Component: React.FC; frames: number; words: Word[] | null };",
    "",
    "export const VIDEOS: VideoEntry[] = [",
    ...videos.map((v) => `  { id: "${v.id}", Component: V${v.n}, frames: F${v.n}, words: ${v.words ? `W${v.n} as Word[]` : "null"} },`),
    "];",
    "",
  );
  return L.join("\n");
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const videos = scan(), text = render(videos);
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (process.argv.includes("--check")) {
    if (old !== text) { console.error("gen-registry: src/videos.generated.ts is out of date; run npm run gen"); process.exit(1); }
    console.log("gen-registry: up to date");
  } else if (old !== text) {
    fs.writeFileSync(OUT, text);
    console.log(`gen-registry: wrote ${videos.length} video(s) to src/videos.generated.ts`);
  } else console.log("gen-registry: up to date");
}
