// Writes src/videos.generated.ts from videos/<id>/Video.tsx (+ words.json when present), sorted by id, and the long
// video chapters from long/<NNN-slug>/ch<N>/ (Video.tsx + chapter.json {"n", "title"}, + words.json when present).
// usage: node scripts/gen-registry.mjs [--check]
//   --check  compare instead of writing; exit 1 when the registry is out of date
// Folder names must match NNN-slug (e.g. 000-bridge), chapter folders chN; other folders are skipped with a warning.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VIDEOS = path.join(ROOT, "videos");
const LONG = path.join(ROOT, "long");
const OUT = path.join(ROOT, "src", "videos.generated.ts");
const ID = /^\d{3}-[a-z0-9-]+$/;
const CH = /^ch\d+$/;

export const scan = (dir = VIDEOS) => {
  const ids = [];
  for (const e of fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }) : []) {
    if (!e.isDirectory() || !fs.existsSync(path.join(dir, e.name, "Video.tsx"))) continue;
    if (!ID.test(e.name)) { console.warn(`gen-registry: skipping videos/${e.name} (folder name must match NNN-slug)`); continue; }
    ids.push(e.name);
  }
  ids.sort();
  const seen = new Map();
  for (const id of ids) {
    const n = id.slice(0, 3);
    if (seen.has(n)) throw new Error(`gen-registry: videos/${seen.get(n)} and videos/${id} share the number ${n}`);
    seen.set(n, id);
  }
  return ids.map((id) => ({ id, n: id.slice(0, 3), words: fs.existsSync(path.join(dir, id, "words.json")) }));
};

// Long video chapters, sorted by id then n. A chapter without Video.tsx or a valid chapter.json is skipped with a warning.
export const scanLong = (dir = LONG) => {
  const out = [];
  const dirs = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name) : []);
  for (const video of dirs(dir)) {
    if (!ID.test(video)) { console.warn(`gen-registry: skipping long/${video} (folder name must match NNN-slug)`); continue; }
    for (const ch of dirs(path.join(dir, video))) {
      const where = `long/${video}/${ch}`, folder = path.join(dir, video, ch);
      if (!CH.test(ch)) { console.warn(`gen-registry: skipping ${where} (chapter folder must match chN)`); continue; }
      if (!fs.existsSync(path.join(folder, "Video.tsx"))) { console.warn(`gen-registry: skipping ${where} (no Video.tsx)`); continue; }
      let meta = null;
      try { meta = JSON.parse(fs.readFileSync(path.join(folder, "chapter.json"), "utf8")); } catch { meta = null; }
      if (!meta || !Number.isInteger(meta.n) || meta.n < 1 || typeof meta.title !== "string" || !meta.title.trim()) {
        console.warn(`gen-registry: skipping ${where} (needs chapter.json {"n": <int>, "title": "<string>"})`); continue;
      }
      out.push({ id: `${video}-${ch}`, video, ch, n: meta.n, title: meta.title, words: fs.existsSync(path.join(folder, "words.json")) });
    }
  }
  out.sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : a.n - b.n));
  return out;
};

export const render = (videos, chapters = []) => {
  const L = [
    "// GENERATED by scripts/gen-registry.mjs - do not edit",
    'import type React from "react";',
    'import type { Word } from "./engine/captions";',
  ];
  for (const v of videos) {
    L.push(`import V${v.n}, { FRAMES as F${v.n} } from "../videos/${v.id}/Video";`);
    if (v.words) L.push(`import W${v.n} from "../videos/${v.id}/words.json";`);
  }
  L.push(
    "",
    "export type VideoEntry = { id: string; Component: React.FC; frames: number; words: Word[] | null };",
    "",
    "export const VIDEOS: VideoEntry[] = [",
    ...videos.map((v) => `  { id: "${v.id}", Component: V${v.n}, frames: F${v.n}, words: ${v.words ? `W${v.n} as Word[]` : "null"} },`),
    "];",
    "",
  );
  chapters.forEach((c, i) => {
    L.push(`import L${i}, { FRAMES as LF${i} } from "../long/${c.video}/${c.ch}/Video";`);
    if (c.words) L.push(`import LW${i} from "../long/${c.video}/${c.ch}/words.json";`);
  });
  L.push(
    ...(chapters.length ? [""] : []),
    "export type LongChapter = { id: string; n: number; title: string; Component: React.FC; frames: number; words: Word[] | null };",
    "",
    "export const LONG_CHAPTERS: LongChapter[] = [",
    ...chapters.map((c, i) => `  { id: "${c.id}", n: ${c.n}, title: ${JSON.stringify(c.title)}, Component: L${i}, frames: LF${i}, words: ${c.words ? `LW${i} as Word[]` : "null"} },`),
    "];",
    "",
  );
  return L.join("\n");
};

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const videos = scan(), chapters = scanLong(), text = render(videos, chapters);
  const old = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : null;
  if (process.argv.includes("--check")) {
    if (old !== text) { console.error("gen-registry: src/videos.generated.ts is out of date; run npm run gen"); process.exit(1); }
    console.log("gen-registry: up to date");
  } else if (old !== text) {
    fs.writeFileSync(OUT, text);
    console.log(`gen-registry: wrote ${videos.length} video(s) and ${chapters.length} long chapter(s) to src/videos.generated.ts`);
  } else console.log("gen-registry: up to date");
}
