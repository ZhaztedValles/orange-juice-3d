// Chapter 1 world: one three.js scene holding every place of the chapter (Notre-Dame outside and inside, the school
// courtyard, the Buonaparte room, Corsica with its sea, ships and boats), each a group shown only in its own shots.
// update(id, f, camera) poses everything for shot `id` at frame f (a pure function of id + f). Sky, light rig, card
// binding and the sea shader follow the sample chapter (long/000-sample/ch1/world.ts).
